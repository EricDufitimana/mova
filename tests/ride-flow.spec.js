import { test, expect } from '@playwright/test';

test('two independent phone sessions negotiate, chat, verify pickup, ride, and pay only afterwards', async ({browser}) => {
  const riderContext = await browser.newContext({viewport:{width:390,height:844}});
  const driverContext = await browser.newContext({viewport:{width:390,height:844}});
  const rider = await riderContext.newPage(), driver = await driverContext.newPage();
  const errors = [];
  for (const page of [rider,driver]) {
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*.cartocdn.com/**', route => route.abort());
  }
  const rb = name => rider.getByRole('button',{name,exact:true});
  const db = name => driver.getByRole('button',{name,exact:true});
  await rider.goto('/');
  await expect(rider.getByText('Shared ride server connected',{exact:true})).toBeVisible();
  await driver.goto('/#driver');
  await driver.getByLabel('Choose your driver plate').selectOption('mv-201');
  await db('Go online with this plate').click();
  await expect(driver.getByRole('heading',{name:'RAD 482 F',exact:true})).toBeVisible();
  await expect(driver.getByText('Online',{exact:true})).toBeVisible();
  await rb('Book this ride').click();
  await rider.getByLabel('Destination',{exact:true}).fill('Kimironko market');
  await rider.getByRole('button',{name:/Negotiate with driver/}).click();
  await rider.getByLabel('Your offer (RWF)',{exact:true}).fill('500');
  await rb('Send request · nothing to pay').click();
  await expect(driver.getByRole('heading',{name:'Waiting for fare agreement'})).toBeVisible();
  await expect(rb('I have paid after the ride')).toHaveCount(0);
  await expect(db('End trip at destination')).toHaveCount(0);
  await rider.getByLabel('Message',{exact:true}).fill('Meet me at the main entrance.'); await rb('Send message').click();
  await expect(driver.getByText('Meet me at the main entrance.',{exact:true})).toBeVisible();
  await driver.getByLabel('Message',{exact:true}).fill('Yes, I can meet you there.'); await db('Send message').click();
  await expect(rider.getByText('Yes, I can meet you there.',{exact:true})).toBeVisible();
  await driver.getByLabel('Counteroffer (RWF)',{exact:true}).fill('750'); await db('Send offer').click();
  await rb('Accept 750 RWF').click();
  await expect(rider.getByText('Locked fare',{exact:true})).toBeVisible();
  const pin = await rider.locator('.pickup-code strong').textContent();
  await expect(driver.locator('.pickup-code')).toHaveCount(0);
  await db('I’m on the way').click(); await db('I have arrived at pickup').click();
  await driver.getByLabel('Rider pickup code').fill('0000'); await db('Verify code & start trip').click();
  await expect(driver.getByRole('alert')).toContainText('Incorrect pickup code');
  await driver.getByLabel('Rider pickup code').fill(pin); await db('Verify code & start trip').click();
  await expect(rider.getByRole('heading',{name:'Trip in progress',exact:true})).toBeVisible();
  await expect(rb('I have paid after the ride')).toHaveCount(0);
  await rider.getByLabel('Message',{exact:true}).fill('Keep this draft while offline');
  await riderContext.setOffline(true);
  await expect(rb('Send message')).toBeDisabled({timeout:15000});
  await riderContext.setOffline(false);
  await expect(rb('Send message')).toBeEnabled({timeout:15000});
  await expect(rider.getByLabel('Message',{exact:true})).toHaveValue('Keep this draft while offline');
  await driver.reload(); await expect(db('End trip at destination')).toBeVisible();
  await db('End trip at destination').click(); await db('Confirm trip completed').click();
  await expect(rb('I have paid after the ride')).toBeVisible();
  await rider.reload(); await rb('Open active ride').click();
  await expect(rider.getByRole('heading',{name:'Trip complete · pay after riding',exact:true})).toBeVisible();
  await rb('Report a problem').click(); await rider.getByLabel('Describe the problem').fill('Need to confirm the wallet number.'); await rb('Record problem').click();
  await expect(rb('I have paid after the ride')).toBeDisabled();
  await expect(driver.getByText('Need to confirm the wallet number.',{exact:true})).toBeVisible();
  await rb('I confirm this issue is resolved').click();
  await rb('I have paid after the ride').click(); await rb('Confirm I have paid').click();
  await db('Confirm receipt').click(); await db('Confirm payment received').click();
  await expect(rider.getByRole('heading',{name:'Ride closed',exact:true})).toBeVisible();
  await rider.screenshot({path:'test-results/rider-receipt-mobile.png',fullPage:true});
  await driver.screenshot({path:'test-results/driver-receipt-mobile.png',fullPage:true});
  expect(await rider.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(await driver.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await rb('Back to bikes').click(); await rb('Book this ride').click();
  await rider.getByLabel('Destination',{exact:true}).fill('Kigali Heights'); await rb('Send request · nothing to pay').click();
  await db('Accept 900 RWF').click(); await db('I’m on the way').click();
  await expect(rider.getByRole('heading',{name:'Driver on the way',exact:true})).toBeVisible();
  await rb('Cancel / no-show · no charge').click(); await rider.getByLabel('Cancellation reason').fill('Driver did not arrive.'); await rb('Confirm cancellation without charge').click();
  await expect(driver.getByRole('heading',{name:'Waiting for a rider.',exact:true})).toBeVisible();
  await expect(rider.getByRole('heading',{name:'Cancelled · no charge',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
  await riderContext.close(); await driverContext.close();
});

test('customer GPS pickup and driver simulation remain shared after refresh and pause', async ({browser}) => {
  const customerContext=await browser.newContext({viewport:{width:390,height:844},geolocation:{latitude:-2.0329,longitude:30.3838},permissions:['geolocation']});
  const driverContext=await browser.newContext({viewport:{width:390,height:844}});
  const customer=await customerContext.newPage(), driver=await driverContext.newPage();
  for(const page of [customer,driver]) await page.route('**/*.tile.openstreetmap.org/**',r=>r.abort());
  await customer.goto('/');
  await customer.getByRole('button',{name:'Use my location',exact:true}).click();
  await expect(customer.locator('.map-heading strong')).toHaveText('My current location');
  await driver.goto('/');await driver.getByRole('link',{name:'Driver',exact:true}).click();
  await driver.getByLabel('Choose your driver plate').selectOption('mv-202');
  await driver.getByRole('button',{name:'Go online with this plate',exact:true}).click();
  await customer.getByRole('button',{name:'View RAE 316 C details',exact:true}).click();
  await customer.getByRole('button',{name:'Book this ride',exact:true}).click();
  await expect(customer.getByLabel('Pickup place')).toHaveValue('My current location');
  await customer.getByLabel('Destination',{exact:true}).fill('Ntunga');
  await customer.getByRole('button',{name:'Send request · nothing to pay',exact:true}).click();
  await driver.getByRole('button',{name:'Accept 3,200 RWF',exact:true}).click();
  await driver.getByLabel('Demo approach duration').selectOption('30000');
  await driver.getByRole('button',{name:'I’m on the way',exact:true}).click();
  const read=page=>page.evaluate(async()=>{const token=localStorage.getItem(location.hash.startsWith('#driver') ? 'mova-driver-session' : 'mova-rider-session');return (await(await fetch('/api/state',{headers:{Authorization:`Bearer ${token}`}})).json()).rides[0];});
  const first=await read(driver);expect(first.pickupCoords.lat).toBeCloseTo(-2.0329);expect(first.tracking.path[0].lat).toBeCloseTo(-1.957409,2);
  await expect.poll(async()=> (await read(customer)).tracking.progress).toBeGreaterThan(.05);
  await driver.getByRole('button',{name:'Pause approach simulation',exact:true}).click();
  const paused=await read(driver), same=await read(customer);
  expect(paused.tracking.paused).toBe(true);expect(same.tracking.progress).toBeCloseTo(paused.tracking.progress,5);
  await customer.reload();await customer.getByRole('button',{name:'Open active ride',exact:true}).click();
  await expect(customer.getByText('Simulation paused',{exact:true})).toBeVisible();
  await driver.reload();await driver.getByRole('button',{name:'Resume approach simulation',exact:true}).click();
  await expect.poll(async()=> (await read(customer)).tracking.progress).toBeGreaterThan(paused.tracking.progress+.03);
  await customer.screenshot({path:'test-results/customer-approach-mobile.png',fullPage:true});
  await driver.screenshot({path:'test-results/driver-approach-mobile.png',fullPage:true});
  expect(await customer.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(await driver.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await customer.getByRole('button',{name:'Cancel / no-show · no charge',exact:true}).click();await customer.getByLabel('Cancellation reason').fill('Simulation test finished');await customer.getByRole('button',{name:'Confirm cancellation without charge',exact:true}).click();
  await customerContext.close();await driverContext.close();
});

test('presentation page shows all bikes and map navigation survives polling and selection', async ({page}) => {
  await page.setViewportSize({width:1600,height:1000});
  await page.route('**/*.tile.openstreetmap.org/**',r=>r.abort());
  await page.goto('/');
  const map=page.locator('.explorer .geo-map-surface');
  await expect(page.locator('.bike-plate-pin')).toHaveCount(16);
  const before=Number(await map.getAttribute('data-map-zoom'));
  await page.getByRole('button',{name:'Zoom map in',exact:true}).click();
  await expect.poll(async()=>Number(await map.getAttribute('data-map-zoom'))).toBeGreaterThan(before);
  await map.hover();await page.mouse.wheel(0,-250);
  await expect.poll(async()=>Number(await map.getAttribute('data-map-zoom'))).toBeGreaterThan(before+1);
  const box=await map.boundingBox();const previousCenter=await map.getAttribute('data-map-center');
  await page.mouse.move(box.x+box.width*.55,box.y+box.height*.55);await page.mouse.down();await page.mouse.move(box.x+box.width*.55+140,box.y+box.height*.55+70,{steps:15});await page.mouse.up();
  await expect.poll(()=>map.getAttribute('data-map-center')).not.toBe(previousCenter);
  await page.getByRole('button',{name:'Show all Ntunga bikes',exact:true}).click();
  await page.locator('.leaflet-marker-icon[title="RAM 410 A"]').click();
  await expect(page.locator('.selected-driver-slot .detail-name h3')).toHaveText('Yves K.');
  const center=await map.getAttribute('data-map-center'), zoom=await map.getAttribute('data-map-zoom');
  // Wait for a real subsequent state poll, then ensure it did not reset the view.
  await page.waitForResponse(response=>response.url().includes('/api/state') && response.status() === 200);
  await expect(map).toHaveAttribute('data-map-center',center);await expect(map).toHaveAttribute('data-map-zoom',zoom);
  await page.screenshot({path:'test-results/ntunga-bike-rank-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Book this ride',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('region',{name:'Ride presentation workspace'})).toBeVisible();
  expect((await page.locator('.booking-page-layout>.geo-map').boundingBox()).width).toBeGreaterThan(600);
  await page.screenshot({path:'test-results/booking-page-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Fullscreen',exact:true}).click();
  expect(await page.locator('.workspace').evaluate(el=>el.scrollHeight>el.clientHeight)).toBe(true);
  await page.locator('.workspace').evaluate(el=>{el.scrollTop=el.scrollHeight;});
  await expect(page.getByRole('button',{name:'Send request · nothing to pay',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Back to bikes',exact:true}).click();
  await expect(page.locator('.bike-plate-pin')).toHaveCount(16);
});
